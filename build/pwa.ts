import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

// A small native PWA build step: static shell only, no runtime/data caching.
export function pwa(): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'earnlearn-static-pwa', apply: 'build',
    configResolved(value) { config = value; },
    async closeBundle() {
      const root = resolve(config.root, config.build.outDir);
      const assets: string[] = [];
      async function visit(dir: string) {
        for (const entry of await readdir(dir, { withFileTypes: true })) {
          const path = join(dir, entry.name);
          if (entry.isDirectory()) await visit(path);
          else if (/\.(?:html|js|css|svg|png|woff2|webmanifest)$/.test(entry.name) && entry.name !== 'sw.js') assets.push(path);
        }
      }
      await visit(root); assets.sort();
      const hash = createHash('sha256');
      for (const path of assets) hash.update(await readFile(path));
      const version = hash.digest('hex').slice(0, 16);
      const urls = assets.map(path => '/' + relative(root, path).split('\\').join('/'));
      const worker = `// Generated by build/pwa.ts. Static shell only; never stores task/API/auth data.
const CACHE = 'earnlearn-shell-${version}';
const ASSETS = ${JSON.stringify(urls)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS.map(url => new Request(url, {cache: 'reload'})))));
});
self.addEventListener('message', event => {
  if (event.data === 'SKIP_WAITING') self.skipWaiting();
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith('earnlearn-shell-') && key !== CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/') || url.pathname.startsWith('/.auth/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(async () => (await caches.open(CACHE)).match('/index.html', {ignoreVary: true})));
  } else if (ASSETS.includes(url.pathname) && !url.search) {
    // Public content-hashed shell assets do not vary by Origin. Module requests
    // include Origin while install-time cache requests may not (Vite sets Vary).
    event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(request, {ignoreVary: true})) || fetch(request)));
  }
});
`;
      await writeFile(join(root, 'sw.js'), worker);
      config.logger.info(`PWA: ${urls.length} static assets, version ${version}`);
    }
  };
}
